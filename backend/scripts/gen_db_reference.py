"""Generate docs/DATABASE_REFERENCE.md from the models and the DML playbook.

    python -m scripts.gen_db_reference          # rewrite the file
    python -m scripts.gen_db_reference --check  # exit 1 if the file is out of date
"""
import enum
import inspect
import sys
from pathlib import Path

import sqlalchemy as sa

from app.db import Base, enums
from scripts import playbook

OUT = Path(__file__).resolve().parents[2] / "docs" / "DATABASE_REFERENCE.md"

GROUPS = [
    ("Users", ["users"]),
    ("Property registry", ["properties", "property_documents", "property_reviews", "property_valuations"]),
    ("ANSH issuance and ownership projection", ["ansh_issuances", "ownership_positions"]),
    ("Marketplace and settlement", ["marketplace_listings", "purchase_orders", "payment_records"]),
    ("Ledger operations and reconciliation", ["ledger_operations", "ledger_events", "ledger_event_cursors",
                                              "reconciliation_cases", "idempotency_records"]),
    ("Collateral financing", ["collateral_pledges", "loans", "credit_assessments", "loan_repayments"]),
    ("Distributions", ["ownership_snapshots", "ownership_snapshot_lines", "distributions",
                       "distribution_entitlements"]),
    ("REIT holdings", ["reit_holdings"]),
    ("Lifecycle and audit", ["asset_events", "audit_events"]),
]


def _type(col: sa.Column) -> str:
    t = col.type
    if isinstance(t, sa.Enum):
        return f"enum `{t.enum_class.__name__}`"
    if isinstance(t, sa.TypeDecorator):
        return "timestamp (UTC)"
    if isinstance(t, sa.String):
        return f"varchar({t.length})"
    if isinstance(t, sa.BigInteger):
        return "bigint"
    return type(t).__name__.lower()


def _default(col: sa.Column) -> str:
    sd = col.server_default
    if sd is None:
        return ""
    arg = sd.arg
    if isinstance(arg, str):
        return f"`{arg}`"
    text = str(arg).lower()
    return {"now()": "now", "true": "`true`", "false": "`false`"}.get(text, f"`{text}`")


def _notes(col: sa.Column) -> str:
    notes = []
    if col.primary_key:
        notes.append("primary key")
    for fk in col.foreign_keys:
        notes.append(f"→ `{fk.column.table.name}.{fk.column.name}`")
    if col.name.endswith("_minor"):
        notes.append("paise")
    if col.name.endswith("_bps"):
        notes.append("basis points")
    return ", ".join(notes)


def _docs() -> dict[str, str]:
    return {m.local_table.name: inspect.cleandoc(m.class_.__doc__ or "") for m in Base.registry.mappers}


def render() -> str:
    tables, docs = Base.metadata.tables, _docs()
    grouped = [t for _, names in GROUPS for t in names]
    assert sorted(grouped) == sorted(tables), "GROUPS must list every table exactly once"
    o = ["# TokANSH — Database Reference", "",
         "> Generated by `backend/scripts/gen_db_reference.py` from the SQLAlchemy models and",
         "> `backend/sql/dml_playbook.sql`. Do not edit by hand; a test fails when this file is stale.",
         "> Design rationale and open decisions are in [`DATABASE.md`](DATABASE.md).", "",
         f"{len(tables)} tables. Part 1 is the schema (DDL), Part 2 the enumerations, Part 3 the DML playbook.", "",
         "## Part 1 — Tables", ""]
    for title, names in GROUPS:
        o += [f"### {title}", ""]
        for name in names:
            t = tables[name]
            o += [f"#### `{name}`", "", docs[name], "", "| Column | Type | Null | Default | Notes |", "|---|---|---|---|---|"]
            for c in t.columns:
                o.append(f"| `{c.name}` | {_type(c)} | {'yes' if c.nullable else 'no'} | {_default(c)} | {_notes(c)} |")
            uniques = sorted(", ".join(c.name for c in u.columns) for u in t.constraints if isinstance(u, sa.UniqueConstraint))
            checks = sorted((str(c.name), str(c.sqltext)) for c in t.constraints
                            if isinstance(c, sa.CheckConstraint) and not getattr(c, "_type_bound", False))
            indexes = sorted((i.name, ", ".join(c.name for c in i.columns)) for i in t.indexes)
            if uniques:
                o += ["", "Unique: " + "; ".join(f"(`{u}`)" for u in uniques) + "."]
            if checks:
                o += ["", "Rules enforced by the database:", ""] + [f"- `{n}`: `{sql}`" for n, sql in checks]
            if indexes:
                o += ["", "Indexes: " + "; ".join(f"`{n}` ({cols})" for n, cols in indexes) + "."]
            o.append("")
    o += ["## Part 2 — Enumerations", "",
          "Stored as `varchar(40)` with a CHECK constraint. Enums marked *proposed* are not in the",
          "specification documents and need team approval.", "", "| Enum | Values | Status |", "|---|---|---|"]
    src = inspect.getsource(enums)
    for name, cls in inspect.getmembers(enums, inspect.isclass):
        if issubclass(cls, enum.Enum) and cls is not enums.S:
            head = next(line for line in src.splitlines() if line.startswith(f"class {name}("))
            status = "proposed" if "PROPOSED" in head else "from the specification"
            o.append(f"| `{name}` | {', '.join(f'`{m.value}`' for m in cls)} | {status} |")
    steps = playbook.load()
    o += ["", "## Part 3 — DML playbook", "",
          "Every `INSERT` and `UPDATE` the backend performs for the demonstration journey, in order,",
          "followed by the main read queries. Source: `backend/sql/dml_playbook.sql`, executed end to end by",
          "`backend/tests/test_dml_playbook.py`.", "",
          "- `:name` is a bind parameter. Identifiers are UUIDs generated by the backend.",
          "- Every `:tx_*` and `:block_*` value is what DRUNIX returned. The application never invents one.",
          "- Money is integer paise: ₹10,000 is `1000000`.",
          "- Each step runs in one database transaction; status guards in `WHERE` make repeats harmless.", ""]
    for step in steps:
        o += [f"### {step['title']}", ""]
        for kind, text in step["items"]:
            o += [text, ""] if kind == "note" else ["```sql", text, "```", ""]
    return "\n".join(o).rstrip() + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date; run: python -m scripts.gen_db_reference")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
