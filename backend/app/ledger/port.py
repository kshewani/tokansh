"""The ledger port: the only way the application reaches DRUNIX (ADR-004, ADR-007).

These are TokANSH internal types (DRUNIX_INTEGRATION section 8), not DRUNIX wire
formats. The production implementation is ``GatewayLedgerClient``. Test doubles
live under ``backend/tests`` only and are never importable as a runtime mode.
"""
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Protocol


class SubmissionState(str, Enum):
    NOT_SUBMITTED = "NOT_SUBMITTED"        # definitively never reached the ledger (e.g. endorsement refused)
    SUBMITTED = "SUBMITTED"                # accepted for ordering; commit not yet confirmed
    COMMIT_CONFIRMED = "COMMIT_CONFIRMED"  # committed and valid
    COMMIT_FAILED = "COMMIT_FAILED"        # committed as invalid
    UNKNOWN = "UNKNOWN"                    # outcome cannot be established now


@dataclass
class LedgerResult:
    state: SubmissionState
    transaction_id: str | None = None      # exactly as returned by DRUNIX; never generated by TokANSH
    validation_code: str | None = None
    block_number: int | None = None
    error_code: str | None = None
    error_message: str | None = None
    payload: dict[str, Any] = field(default_factory=dict)


class LedgerUnavailable(Exception):
    """The adapter could not be reached or is not configured. Nothing was sent to DRUNIX."""

    def __init__(self, message: str, code: str = "LEDGER_UNAVAILABLE"):
        super().__init__(message)
        self.code = code
        self.message = message


class LedgerQueryError(Exception):
    """A read (evaluate) was rejected by the chaincode or adapter."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


class LedgerPort(Protocol):
    def submit(self, *, function: str, args: list[str], operation_id: str,
               correlation_id: str | None) -> LedgerResult: ...

    def evaluate(self, *, function: str, args: list[str]) -> dict[str, Any]: ...

    def commit_status(self, transaction_id: str) -> LedgerResult: ...

    def health(self) -> dict[str, Any]: ...
